export const Home = () => {
  const [visibleSections, setVisibleSections] = useState([]);
  const [scrollIndicatorHidden, setScrollIndicatorHidden] = useState(false);
  const intro = useRef();
  const projectOne = useRef();
  const projectTwo = useRef();
  const projectThree = useRef();
  const details = useRef();

  useEffect(() => {
    const sections = [intro, projectOne, projectTwo, projectThree, details];

    const sectionObserver = new IntersectionObserver(
      (entries, observer) => {
        entries.forEach(entry => {
          if (entry.isIntersecting) {
            const section = entry.target;
            observer.unobserve(section);
            setVisibleSections(prev => (prev.includes(section) ? prev : [...prev, section]));
          }
        });
      },
      { rootMargin: '0px 0px -10% 0px', threshold: 0.1 }
    );

    const indicatorObserver = new IntersectionObserver(
      ([entry]) => {
        if (entry) setScrollIndicatorHidden(!entry.isIntersecting);
      },
      { rootMargin: '-100% 0px 0px 0px' }
    );

    sections.forEach(section => {
      if (section.current) sectionObserver.observe(section.current);
    });

    if (intro.current) indicatorObserver.observe(intro.current);

    return () => {
      sectionObserver.disconnect();
      indicatorObserver.disconnect();
    };
  }, []);

  return (
    <div className={styles.home}>
      <Intro
        id="intro"
        sectionRef={intro}
        scrollIndicatorHidden={scrollIndicatorHidden}
      />
      <ProjectSummary
        id="project-1"
        sectionRef={projectOne}
        visible={visibleSections.includes(projectOne.current)}
        index={1}
        title="Proplytics — Multi-Tenant Real Estate CRM"
        description="Architected multi-tenant CRM microservices with FastAPI, Celery, multi-modal WhatsApp LLM agent, and property platform integrations (Bayut & PropertyFinder)."
        buttonText="View website"
        buttonLink="https://proplytics.ae/"
        model={{
          type: 'laptop',
          alt: 'Proplytics multi-tenant CRM backend architecture',
          textures: [
            {
              srcSet: `${proplyticsDark} 1280w, ${proplyticsDark} 2560w`,
              placeholder: proplyticsDark,
            },
          ],
        }}
      />
      <ProjectSummary
        id="project-2"
        alternate
        sectionRef={projectTwo}
        visible={visibleSections.includes(projectTwo.current)}
        index={2}
        title="Scaffold — AI Agent Platform for Creatives"
        description="Built async backend infrastructure with FastAPI, Supabase, Celery, and Redis enabling automated AI agent workflows for ad, logo, and content generation."
        buttonText="View project details"
        buttonLink="https://github.com/sikandar-rajpoot"
        model={{
          type: 'phone',
          alt: 'Scaffold AI agent system',
          textures: [
            {
              srcSet: `${gamestackTexture} 375w, ${gamestackTextureLarge} 750w`,
              placeholder: gamestackTexturePlaceholder,
            },
            {
              srcSet: `${gamestackTexture2} 375w, ${gamestackTexture2Large} 750w`,
              placeholder: gamestackTexture2Placeholder,
            },
          ],
        }}
      />
      <ProjectSummary
        id="project-3"
        sectionRef={projectThree}
        visible={visibleSections.includes(projectThree.current)}
        index={3}
        title="TruckRoute Planner — Route & Compliance API"
        description="HOS-compliant truck routing engine built with Django REST Framework, Celery spatial queries, FMCSA compliance rules, and ELD log generation."
        buttonText="View project details"
        buttonLink="/projects/slice"
        model={{
          type: 'laptop',
          alt: 'TruckRoute Planner API',
          textures: [
            {
              srcSet: `${sliceTexture} 800w, ${sliceTextureLarge} 1920w`,
              placeholder: sliceTexturePlaceholder,
            },
          ],
        }}
      />
      <Profile
        sectionRef={details}
        visible={visibleSections.includes(details.current)}
        id="details"
      />
      <Footer />
    </div>
  );
};
